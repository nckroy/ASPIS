//! Traces for TLC (kernel specification, "Model checking"; trace
//! validation, Cirstea and others, arXiv 2404.16075): seeded runs of
//! ksched::donation, each state projected onto the spec's record. With
//! `KSCHED_TRACE_OUT` set, they are written there as a TLA+ module, which
//! `specs/SchedDonationTrace.tla` checks step by step against the spec's
//! `Next`; `cargo xtask tlc` does both. Without it, the runs only check the
//! invariants.
//!
//! The universe is the trace model's constants (specs/SchedDonationTrace.cfg):
//! four threads, three replies, two contexts, every action enabled. Two
//! contexts make non-donating calls, and their replies and cancels, reachable.

mod common;

use common::Lcg;
use common::actions::{self, Flags};
use common::store::{Host, project};

const NT: usize = 4;
const NR: usize = 3;
const NS: usize = 2;
/// The trace model's TepInit.
const TEP: [usize; 2] = [2, 3];

fn traces(count: u64, steps: usize) -> Vec<Vec<String>> {
    let flags = Flags {
        destroy: true,
        set_tep: true,
        suspend: true,
        refine: false,
        walks: true,
    };
    let mut out = vec![];
    for seed in 0..count {
        let mut rng = Lcg(0x7ace + seed);
        let mut h = Host::init(NT, NR, NS, &TEP);
        let mut trace = vec![project(&mut h).to_tla()];
        for _ in 0..steps {
            let Some(op) = actions::pick(&mut h, &mut rng, flags) else {
                break;
            };
            actions::apply(&mut h, op);
            h.check();
            trace.push(project(&mut h).to_tla());
        }
        out.push(trace);
    }
    out
}

#[test]
fn write_traces() {
    let count = std::env::var("KSCHED_TRACES")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(100);
    let steps = std::env::var("KSCHED_TRACE_STEPS")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(80);
    let ts = traces(count, steps);
    let Ok(path) = std::env::var("KSCHED_TRACE_OUT") else {
        return;
    };
    let mut m = String::new();
    // A build artifact, written into build/ and never committed, so it
    // carries no copyright tags.
    m.push_str("---- MODULE SchedDonationTraces ----\n");
    m.push_str("\\* Generated by crates/ksched/tests/donation_traces.rs.\n");
    m.push_str("Traces == <<\n");
    let body: Vec<String> = ts
        .iter()
        .map(|t| format!("<<\n{}\n>>", t.join(",\n")))
        .collect();
    m.push_str(&body.join(",\n"));
    m.push_str("\n>>\n====\n");
    std::fs::write(&path, m).unwrap_or_else(|e| panic!("{path}: {e}"));
}

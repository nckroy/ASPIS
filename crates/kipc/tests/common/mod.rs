//! Shared test support: a seeded generator, an IPC store in vectors, and
//! the actions of the TLA+ specs with their projections.

// Objects are numbered from 1, as in the specs, and loops over them index
// the store's vectors by those numbers.
#![allow(dead_code, clippy::needless_range_loop)]

pub mod ec_actions;
pub mod ep_actions;
pub mod store;

/// A small seeded generator (Knuth's MMIX constants), so failures repeat.
#[derive(Clone, Copy, Debug)]
pub struct Lcg(pub u64);

impl Lcg {
    pub fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        self.0 >> 33
    }

    /// A number below `n`, which must not be 0.
    pub fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }

    pub fn chance(&mut self, percent: u64) -> bool {
        self.below(100) < percent
    }
}

/// A preemption check that finds an interrupt pending at random, for the
/// advance's and the badge cancel's preemption points.
pub struct Chance(pub Lcg, pub u64);

impl kcap::preempt::Pending for Chance {
    fn pending(&mut self) -> bool {
        self.0.chance(self.1)
    }
}

/// The number of seeded runs: the per-change count, times
/// `KSCHED_RUNS_SCALE` if it is set, as the nightly workflow sets it: the
/// variable C12's seeded tests read, so one setting scales both crates.
pub fn runs(per_change: u64) -> u64 {
    let scale = std::env::var("KSCHED_RUNS_SCALE")
        .ok()
        .and_then(|v| v.parse::<u64>().ok())
        .unwrap_or(1)
        .max(1);
    per_change.saturating_mul(scale)
}

/// Writes traces as the TLA+ module `name`, to the path in `env`, if it is
/// set: a build artifact, never committed, so it carries no copyright tags.
pub fn write_traces(env: &str, name: &str, by: &str, traces: &[Vec<String>]) {
    let Ok(path) = std::env::var(env) else {
        return;
    };
    let mut m = String::new();
    m.push_str(&format!("---- MODULE {name} ----\n"));
    m.push_str(&format!("\\* Generated by {by}.\n"));
    m.push_str("Traces == <<\n");
    let body: Vec<String> = traces
        .iter()
        .map(|t| format!("<<\n{}\n>>", t.join(",\n")))
        .collect();
    m.push_str(&body.join(",\n"));
    m.push_str("\n>>\n====\n");
    std::fs::write(&path, m).unwrap_or_else(|e| panic!("{path}: {e}"));
}

/// The traces' count and length: `KIPC_TRACES` and `KIPC_TRACE_STEPS`, or
/// the defaults.
pub fn trace_shape() -> (u64, usize) {
    let count = std::env::var("KIPC_TRACES")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(100);
    let steps = std::env::var("KIPC_TRACE_STEPS")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(80);
    (count, steps)
}

/// A function on 1..n, as a TLA+ tuple.
pub fn tup<T>(xs: &[T], f: impl Fn(&T) -> String) -> String {
    let body: Vec<String> = xs.iter().map(f).collect();
    format!("<<{}>>", body.join(", "))
}

pub fn tla_bool(b: &bool) -> String {
    if *b { "TRUE".into() } else { "FALSE".into() }
}

pub fn tla_str(x: &&str) -> String {
    format!("\"{x}\"")
}

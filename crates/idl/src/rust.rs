    fn closed_enum(&mut self, id: TypeId, name: &str, docs: &[String], width: IntType) {
        let values = self.s.values(id);
        let w = width.word();
        self.docs(docs);
        self.l("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]");
        self.l(format!("#[repr({w})]"));
        self.open(format!("pub enum {name} {{"));
        for v in &values {
            let d = self.value_docs(id, v.value);
            self.docs(&d);
            self.l(format!("{} = {},", camel(v.name), v.value));
        }
        self.close("}");
        self.l("");
        self.open(format!("impl {name} {{"));
        self.l("/// Decodes the value: one the type doesn't declare is malformed.");
        self.open("pub fn decode(r: &mut rt::wire::Reader<'_>, _cx: &mut rt::wire::DecodeCx) -> ::core::result::Result<Self, rt::wire::DecodeError> {");
        self.open(format!("::core::result::Result::Ok(match r.{w}()? {{"));
        for v in &values {
            self.l(format!("{} => Self::{},", v.value, camel(v.name)));
        }
        self.l("_ => return ::core::result::Result::Err(rt::wire::DecodeError::Malformed),");
        self.close("})");
        self.close("}");
        self.l("");
        self.l("/// The value's number.");
        self.open(format!("pub fn value(self) -> {w} {{"));
        self.open("match self {");
        for v in &values {
            self.l(format!("Self::{} => {},", camel(v.name), v.value));
        }
        self.close("}");
        self.close("}");
        self.l("");
        self.l("/// The value's name.");
        self.open("pub fn name(self) -> &'static str {");
        self.open("match self {");
        for v in &values {
            self.l(format!("Self::{} => {},", camel(v.name), lit(v.name)));
        }
        self.close("}");
        self.close("}");
        self.l("");
        self.open("pub fn encode(&self, w: &mut rt::wire::Writer<'_>, _cx: &rt::wire::EncodeCx) -> ::core::result::Result<(), rt::wire::EncodeError> {");
        self.l(format!("w.{w}(self.value())"));
        self.close("}");
        self.l("");
        self.open("pub fn to_json(&self, j: &mut rt::json::JsonWriter<'_>, _minor: u16) {");
        self.l("j.string(self.name());");
        self.close("}");
        self.close("}");
        self.l("");
        self.elem_impl(name, false);
        self.l("#[cfg(feature = \"alloc\")]");
        self.open(format!("impl rt::view::IntoOwned for {name} {{"));
        self.l("type Owned = Self;");
        self.l("fn into_owned(self) -> Self { self }");
        self.close("}");
    }

    /// An open enum, or a flags type: a newtype over its width, so every
    /// value is representable and preserved.
    fn newtype(
        &mut self,
        id: TypeId,
        name: &str,
        docs: &[String],
        width: IntType,
        flags: bool,
        closed: bool,
    ) {
        let u = id.unit;
        let since0 = self.s.type_since(id);
        let mut values: Vec<_> = self
            .s
            .values(id)
            .into_iter()
            .map(|v| {
                let attrs = self.value_attrs(id, v.value);
                (self.since(u, &attrs, since0), v)
            })
            .collect();
        let w = width.word();
        self.docs(docs);
        self.l("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Default)]");
        self.l(format!("pub struct {name}(pub {w});"));
        self.l("");
        self.open(format!("impl {name} {{"));
        for (_, v) in &values {
            let d = self.value_docs(id, v.value);
            self.docs(&d);
            self.l(format!(
                "pub const {}: {name} = {name}({});",
                upper(v.name),
                v.value
            ));
        }
        let any_since = values.iter().any(|(s, _)| *s > 0);
        self.l("");
        self.l("/// The newest `since` minor of what the value holds: 0 for what came with the first minor, or isn't declared.");
        self.open("pub fn since(self) -> u16 {");
        if !any_since {
            self.l("0");
        } else if flags {
            self.l("let mut s = 0;");
            for (since, v) in values.iter().filter(|(s, _)| *s > 0) {
                self.l(format!(
                    "if self.0 & {} != 0 {{ s = s.max({since}); }}",
                    v.value
                ));
            }
            self.l("s");
        } else {
            self.open("match self.0 {");
            for (since, v) in values.iter().filter(|(s, _)| *s > 0) {
                self.l(format!("{} => {since},", v.value));
            }
            self.l("_ => 0,");
            self.close("}");
        }
        self.close("}");
        self.l("");
        let mask = values.iter().fold(0u64, |m, (_, v)| m | v.value);
        self.l("/// Decodes the value. A closed type's undeclared bits are malformed.");
        self.open("pub fn decode(r: &mut rt::wire::Reader<'_>, cx: &mut rt::wire::DecodeCx) -> ::core::result::Result<Self, rt::wire::DecodeError> {");
        self.l(format!("let v = {name}(r.{w}()?);"));
        if closed && flags {
            self.l(format!(
                "if v.0 & !{mask}{w} != 0 {{ return ::core::result::Result::Err(rt::wire::DecodeError::Malformed); }}"
            ));
        }
        self.l("cx.value(v.since());");
        self.l("::core::result::Result::Ok(v)");
        self.close("}");
        self.l("");
        self.open("pub fn encode(&self, w: &mut rt::wire::Writer<'_>, cx: &rt::wire::EncodeCx) -> ::core::result::Result<(), rt::wire::EncodeError> {");
        if closed && flags {
            self.l(format!(
                "if self.0 & !{mask}{w} != 0 {{ return ::core::result::Result::Err(rt::wire::EncodeError::Bounds); }}"
            ));
        }
        self.l("cx.value(self.since())?;");
        self.l(format!("w.{w}(self.0)"));
        self.close("}");
        self.l("");
        self.l("/// Writes the value's JSON, as minor `minor` reads it.");
        self.open("pub fn to_json(&self, j: &mut rt::json::JsonWriter<'_>, minor: u16) {");
        self.l("let _ = minor;");
        let rest = if width == IntType::U64 {
            "j.u64_string(rest)"
        } else {
            "j.uint(u64::from(rest))"
        };
        if flags {
            values.sort_by_key(|(_, v)| v.value);
            self.l("j.begin_array();");
            self.l("let mut rest = self.0;");
            for (since, v) in &values {
                let guard = if *since > 0 {
                    format!(" && minor >= {since}")
                } else {
                    String::new()
                };
                self.l(format!(
                    "if self.0 & {}{w} != 0{guard} {{ j.string({}); rest &= !{}{w}; }}",
                    v.value,
                    lit(v.name),
                    v.value
                ));
            }
            self.l(format!("if rest != 0 {{ {rest}; }}"));
            self.l("j.end_array();");
        } else {
            self.open("match self.0 {");
            for (since, v) in &values {
                let guard = if *since > 0 {
                    format!(" if minor >= {since}")
                } else {
                    String::new()
                };
                self.l(format!("{}{guard} => j.string({}),", v.value, lit(v.name)));
            }
            self.l(format!("rest => {rest},"));
            self.close("}");
        }
        self.close("}");
        self.close("}");
        self.l("");
        self.elem_impl(name, false);
        if flags {
            self.open(format!("impl core::ops::BitOr for {name} {{"));
            self.l("type Output = Self;");
            self.l("fn bitor(self, o: Self) -> Self { Self(self.0 | o.0) }");
            self.close("}");
            self.l("");
        }
        self.l("#[cfg(feature = \"alloc\")]");
        self.open(format!("impl rt::view::IntoOwned for {name} {{"));
        self.l("type Owned = Self;");
        self.l("fn into_owned(self) -> Self { self }");
        self.close("}");
    }

    fn value_attrs(&self, id: TypeId, value: u64) -> Vec<ast::Attr> {
        match self.s.def(id) {
            Def::Enum { values, .. } => values
                .iter()
                .find_map(|v| match v {
                    ast::Value::Value {
                        attrs, value: lit, ..
                    } if lit.value.and_then(|x| u64::try_from(x).ok()) == Some(value) => {
                        Some(attrs.clone())
                    }
                    _ => None,
                })
                .unwrap_or_default(),
            _ => Vec::new(),
        }
    }


//! libFuzzer dictionaries from a grammar (docs/design/call-language.md,
//! "Layout", dictionaries; ADR 0068).
//!
//! A dictionary holds every literal of the grammar ([`Grammar::literals`])
//! and the "interesting" integers of each core width: 0, 1, the largest
//! unsigned value, and the signed boundaries. Integers are written in the
//! grammar's byte order: big-endian for the grammars that use `core`
//! (ADR 0062, rule 2), little-endian for the formats that keep it, such as
//! `initfs` (ADR 0037). The caller says which.
//!
//! The output is deterministic: entries are deduplicated and sorted.
//! `cargo xtask fuzz-dict` writes one per grammar under `build/fuzz/dict/`.

use alloc::{collections::BTreeSet, string::String, vec::Vec};
use core::fmt::Write as _;

use crate::Grammar;

/// The byte order of a grammar's integers.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Endian {
    Big,
    Little,
}

/// libFuzzer's longest dictionary entry, in octets. A longer literal is
/// left out: libFuzzer refuses a dictionary that holds one.
pub const MAX_ENTRY: usize = 64;

/// The interesting values of each width, as unsigned numbers of that
/// width: 0, 1, the largest, the largest signed and the smallest signed.
fn interesting(endian: Endian) -> Vec<Vec<u8>> {
    let mut out = Vec::new();
    for octets in [1usize, 2, 4, 8] {
        let bits = 8 * octets as u32;
        let max = u64::MAX >> (64 - bits);
        let smax = max >> 1;
        for v in [0, 1, max, smax, smax + 1] {
            let be = v.to_be_bytes();
            let mut bytes = be[8 - octets..].to_vec();
            if endian == Endian::Little {
                bytes.reverse();
            }
            out.push(bytes);
        }
    }
    out
}

/// One entry, quoted as libFuzzer reads it: printable ASCII as itself,
/// `\\` and `\"` escaped, every other octet as `\xHH`.
fn quote(entry: &[u8], out: &mut String) {
    out.push('"');
    for &b in entry {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            0x20..=0x7E => out.push(b as char),
            _ => {
                let _ = write!(out, "\\x{b:02X}");
            }
        }
    }
    out.push('"');
}

/// The grammar's libFuzzer dictionary, one entry per line after a comment
/// naming it.
pub fn libfuzzer(g: &Grammar, name: &str, endian: Endian) -> String {
    let mut entries: BTreeSet<Vec<u8>> = g
        .literals()
        .filter(|l| l.len() <= MAX_ENTRY)
        .map(<[u8]>::to_vec)
        .collect();
    entries.extend(interesting(endian));
    let mut out = String::new();
    let order = match endian {
        Endian::Big => "big",
        Endian::Little => "little",
    };
    let _ = writeln!(
        out,
        "# {name}: the grammar's literals, and {order}-endian integers; generated by cargo xtask fuzz-dict."
    );
    for e in entries {
        quote(&e, &mut out);
        out.push('\n');
    }
    out
}
